"""Rebuild webfonts with: python -m pip install 'fonttools[woff]'
Then run: python scripts/build-font-subsets.py
Generated files are committed; Python is not needed during deployment.
"""
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from hashlib import sha256
from io import BytesIO
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "public/fonts/OPlusSans3-Regular.ttf"
OUTPUT = ROOT / "public/fonts/oppo-sans"
CHUNK_SIZE = 256


def unicode_range(codepoints):
    ranges = []
    start = end = None
    for value in sorted(codepoints):
        if end is not None and value == end + 1:
            end = value
        else:
            if start is not None:
                ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
            start = end = value
    if start is not None:
        ranges.append(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}")
    return ",".join(ranges)


def build():
    original = SOURCE.read_bytes()
    with TTFont(BytesIO(original)) as font:
        supported = set(font.getBestCmap())
    counts = Counter()
    for directory in ("content", "app", "components"):
        for file in sorted((ROOT / directory).rglob("*")):
            if file.suffix in {".html", ".md", ".json", ".jsx"}:
                counts.update(map(ord, file.read_text(encoding="utf-8")))

    # Frequency grouping keeps current articles compact. Unused characters are
    # still shipped in separate ranges, so new articles/comments need no rebuild.
    basic = sorted(cp for cp in supported if cp <= 0x24F)
    frequent = sorted(supported.intersection(counts).difference(basic), key=lambda cp: (-counts[cp], cp))
    remaining = sorted(supported.difference(basic).difference(frequent))
    groups = [basic]
    for sequence in (frequent, remaining):
        groups.extend(sequence[i:i + CHUNK_SIZE] for i in range(0, len(sequence), CHUNK_SIZE))
    assert sum(map(len, groups)) == len(supported)
    OUTPUT.mkdir(parents=True, exist_ok=True)

    def emit(item):
        index, codepoints = item
        font = TTFont(BytesIO(original), recalcTimestamp=False)
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        options.name_languages = ["*"]
        worker = subset.Subsetter(options=options)
        worker.populate(unicodes=codepoints)
        worker.subset(font)
        font.flavor = "woff2"
        buffer = BytesIO()
        font.save(buffer)
        font.close()
        data = buffer.getvalue()
        with TTFont(BytesIO(data)) as check:
            missing = set(codepoints).difference(check.getBestCmap())
            assert not missing, f"Character loss in subset {index}: {missing}"
        filename = f"oppo-{index:03d}.{sha256(data).hexdigest()[:16]}.woff2"
        (OUTPUT / filename).write_bytes(data)
        return {"url": f"/fonts/oppo-sans/{filename}", "bytes": len(data),
                "characters": len(codepoints), "unicodeRange": unicode_range(codepoints)}

    with ThreadPoolExecutor(max_workers=4) as pool:
        entries = list(pool.map(emit, enumerate(groups)))
    css = "/* Generated by scripts/build-font-subsets.py; do not edit. */\n" + "\n".join(
        '@font-face{font-family:"OPPO Sans";src:url("' + entry["url"] + '") format("woff2");'
        'font-weight:400;font-style:normal;font-display:swap;unicode-range:' + entry["unicodeRange"] + ';}'
        for entry in entries
    ) + "\n"
    (ROOT / "app/font-faces.css").write_text(css, encoding="utf-8")
    (ROOT / "lib/font-faces.js").write_text(
        "// Generated by scripts/build-font-subsets.py; shared with app/font-faces.css.\n"
        "export const fontFaces = " + json.dumps(css) + ";\n", encoding="utf-8")
    manifest = {"sourceSha256": sha256(original).hexdigest(), "sourceBytes": len(original),
                "characters": len(supported), "subsets": entries}
    (ROOT / "lib/font-manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"subsets": len(entries), "characters": len(supported), "siteCharacters": len(frequent),
                      "totalBytes": sum(entry["bytes"] for entry in entries), "basicBytes": entries[0]["bytes"]}))


if __name__ == "__main__":
    build()
