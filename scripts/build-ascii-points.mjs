import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
import sharp from 'sharp';
import { characterPoints, HERO_SOURCE } from '../lib/ascii-character.js';
import { encodeAsciiPoints } from '../lib/ascii-points-format.js';

// Match the browser's drawImage stretch instead of Sharp's default cover crop.
const pixels = await sharp(`public${HERO_SOURCE}`).resize(1280, 550, { fit: 'fill' }).ensureAlpha().raw().toBuffer();
const data = characterPoints(pixels, 1280, 550, 4);
const bytes = Buffer.from(encodeAsciiPoints(data));
const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
const url = `/ascii/character.${hash}.bin`;
await fs.mkdir('public/ascii', { recursive: true });
await fs.writeFile(`public${url}`, bytes);
await fs.writeFile('lib/ascii-asset.js', `// Generated by scripts/build-ascii-points.mjs; regenerate when the artwork or sampling changes.\nexport const ASCII_POINTS_URL = '${url}';\n`);
console.log(`ASCII: ${data.tones.length} points, ${bytes.length} bytes -> ${url}`);
